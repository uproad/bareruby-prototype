# Every GPIO a Raspberry Pi Pico 1 brings out to its header, pulsed one after another
# with nothing between the writes. GP0 through GP22 and GP26 through GP28 are the ones a
# circuit can be wired to; GP23, GP24, GP25 and GP29 are not on the header at all — they
# are the SMPS mode control, the VBUS sense line, the onboard LED and the VSYS divider.
#
# The writes are straight-line rather than a loop over an array so that nothing but the
# pin writes is on the path. How fast it runs is read off a pin: the high time of one pulse
# is a single write pair, and the period of GP0 is one whole sweep.

